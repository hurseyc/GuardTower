#!/usr/bin/env python3
"""Writes mkdocs.yml's nav from each page's front matter (section + order),
the same ordering the in-app wiki uses (internal/api/handlers_docs.go).

    python3 scripts/mkdocs_nav.py && mkdocs build --strict
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SECTIONS = ["Getting started", "Setup", "Operation", "Family DNS", "Admin", "Reference"]

pages = []
for p in sorted((ROOT / "docs").rglob("*.md")):
    rel = p.relative_to(ROOT / "docs").as_posix()
    if rel.startswith("dev/") or p.name.startswith("_"):
        continue
    fm = re.match(r"^---\n(.*?)\n---\n", p.read_text(encoding="utf-8"), re.S)
    meta = dict(re.findall(r"^(\w+):\s*(.*)$", fm.group(1), re.M)) if fm else {}
    pages.append((SECTIONS.index(meta.get("section", "Reference")) if meta.get("section") in SECTIONS else len(SECTIONS),
                  int(meta.get("order", 999)), meta.get("title", p.stem).strip().strip('"'), meta.get("section", "Reference"), rel))

nav = ["nav:"]
current = None
for _, _, title, section, rel in sorted(pages):
    if rel == "index.md":
        nav.insert(1, f"  - Home: {rel}")
        continue
    if section != current:
        nav.append(f'  - "{section}":')
        current = section
    nav.append(f'      - "{title.replace(chr(34), chr(39))}": {rel}')

cfg = ROOT / "mkdocs.yml"
text = cfg.read_text(encoding="utf-8")
text = re.sub(r"(?ms)^nav:\n(?:  .*\n?)*", "", text).rstrip() + "\n\n# Generated by scripts/mkdocs_nav.py; don't edit by hand.\n" + "\n".join(nav) + "\n"
text = text.replace("\n\n# Generated by scripts/mkdocs_nav.py; don't edit by hand.\n\n# Generated", "\n\n# Generated")
cfg.write_text(text, encoding="utf-8")
print(f"wrote nav for {len(pages)} pages")
